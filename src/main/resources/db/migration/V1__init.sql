CREATE TABLE frames (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255), image_url VARCHAR(255), price INTEGER NOT NULL, description VARCHAR(255)
);

CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255), age INTEGER NOT NULL, email VARCHAR(255), password VARCHAR(255), role VARCHAR(255),
    status VARCHAR(255), battery_level INTEGER, school VARCHAR(255), university VARCHAR(255),
    coins INTEGER NOT NULL DEFAULT 100, active_frame_id INTEGER REFERENCES frames(id)
);

CREATE TABLE friendships (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER REFERENCES users(id), friend_id INTEGER REFERENCES users(id), status VARCHAR(255)
);
CREATE TABLE blocks (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blocker_id INTEGER REFERENCES users(id), blocked_id INTEGER REFERENCES users(id)
);
CREATE TABLE locations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER UNIQUE REFERENCES users(id), lat DOUBLE PRECISION NOT NULL, lng DOUBLE PRECISION NOT NULL,
    timestamp TIMESTAMP
);
CREATE TABLE meet_requests (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id INTEGER REFERENCES users(id), receiver_id INTEGER REFERENCES users(id),
    meet_lat DOUBLE PRECISION NOT NULL, meet_lng DOUBLE PRECISION NOT NULL, status VARCHAR(255), created_at TIMESTAMP
);
CREATE TABLE messages (
    id INTEGER PRIMARY KEY, sender_id INTEGER REFERENCES users(id), receiver_id INTEGER REFERENCES users(id),
    content VARCHAR(255), timestamp TIMESTAMP
);
CREATE TABLE posts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER REFERENCES users(id), image_url VARCHAR(255), caption VARCHAR(255), created_at TIMESTAMP
);
CREATE TABLE post_likes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER REFERENCES users(id), post_id INTEGER REFERENCES posts(id)
);
CREATE TABLE post_comments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER REFERENCES users(id), post_id INTEGER REFERENCES posts(id), content VARCHAR(255), created_at TIMESTAMP
);
CREATE TABLE stories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER REFERENCES users(id), image_url VARCHAR(255), caption VARCHAR(255), created_at TIMESTAMP, expires_at TIMESTAMP
);
CREATE TABLE user_frames (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER REFERENCES users(id), frame_id INTEGER REFERENCES frames(id), purchased_at TIMESTAMP
);
